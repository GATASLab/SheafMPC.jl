import json, statistics as st
# Table II's fixed-team row from E119's in-loop arm: the E106 loop rerun with the whole certificate, including its
# fleet linear term q, inside the timed step. Same definitions as results/e106_overrun_full.json "fields".
e106 = json.load(open("results/e106_overrun_full.json"))["sizes"]["4096"]["controllers"]["team_resp_quarter"]
ratio, med_ms, max_ms, met, fq, qold = [], [], [], [], [], []
for s in range(1, 6):
    p = json.load(open(f"results/parts119/e119_n4096_seed{s}.json"))
    o = p["arms"]["inloop"]
    central = p["e106"]["closed_loop_cost"] / e106["cost_ratio_per_seed"][s - 1]   # converged centralized MPC, same seed
    ratio.append(o["closed_loop_cost"] / central)
    med_ms.append(1e3 * o["t_total"]["median"]); max_ms.append(1e3 * o["t_total"]["max"]); met.append(o["met_frac"])
    fq.append(1e3 * o["t_fastq"]["median"]); qold.append(1e3 * o["t_qc71"]["median"])
    assert o["relerr_max"] <= 1e-10
m = {
 "cnFqCost": f"{st.median(ratio):.2f}",
 "cnFqCostMax": f"{max(ratio):.2f}",
 "cnFqStepMs": f"{st.median(med_ms):.0f}",
 "cnFqMsMax": f"{max(max_ms):.0f}",
 "cnFqMet": f"{100 * st.mean(met):.0f}",
 "cnFqMs": f"{st.median(fq):.0f}",
 "cnFqOldMs": f"{st.median(qold):.0f}",
}
with open("preamble/numbers_e119.tex", "w") as f:
    f.write("% generated by scripts/gen_numbers_e119.py from results/parts119 (HPG jobs 50488099-50488101)\n")
    for k, v in m.items():
        f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
print(open("preamble/numbers_e119.tex").read())
